let currentLang = 'ar';

export function normalizeLang(value) {
  return value === 'en' ? 'en' : 'ar';
}

export function getLang() {
  return currentLang;
}

export function t(key, vars = {}) {
  const table = messages[currentLang] || messages.ar;
  let value = table[key] ?? messages.ar[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.body?.setAttribute('data-lang', currentLang);

  for (const node of document.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of document.querySelectorAll('[data-i18n-html]')) {
    node.innerHTML = t(node.dataset.i18nHtml);
  }
  for (const node of document.querySelectorAll('[data-i18n-placeholder]')) {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  }
  for (const node of document.querySelectorAll('[data-i18n-title]')) {
    node.setAttribute('title', t(node.dataset.i18nTitle));
  }
  for (const node of document.querySelectorAll('[data-i18n-aria]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  }

  document.title = t('meta.title');
  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.querySelector('.lang-label').textContent = currentLang === 'ar' ? 'EN' : 'ع';
    toggle.setAttribute('aria-label', currentLang === 'ar' ? 'Switch to English' : 'التبديل إلى العربية');
  }

  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
}

export function setLang(nextLang, { persist = true } = {}) {
  currentLang = normalizeLang(nextLang);
  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEY, currentLang);
    } catch {
      /* storage disabled */
    }
  }
  applyTranslations();
  return currentLang;
}

export function initI18n() {
  let saved = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch {
    /* storage disabled */
  }
  const browserLang = (navigator.language || 'ar').toLowerCase().startsWith('ar') ? 'ar' : 'en';
  currentLang = normalizeLang(saved || browserLang);
  applyTranslations();
  const toggle = document.getElementById('lang-toggle');
  toggle?.addEventListener('click', () => {
    setLang(currentLang === 'ar' ? 'en' : 'ar');
  });
  return currentLang;
}
